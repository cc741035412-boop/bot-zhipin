import { test, expect } from '@playwright/test'
import { POKE_PITCHES } from '../../site/.vitepress/meta.mjs'

const slug = 'demo-weekly-digest'
const card = (page) => page.locator(`[data-testid="bot-card"][data-slug="${slug}"]`)
test.beforeEach(async ({ page, context }) => {
  await page.route('**/api/stats', (route) => route.fulfill({ json: { ok: true, heat: {}, byKind: {} } }))
  await page.route('**/api/click', (route) => route.fulfill({ json: { ok: true, counted: true, heat: 1 } }))
  await context.route('https://x.ai/**', (route) => route.fulfill({ body: 'mock import' }))
  await page.addInitScript(() => Object.defineProperty(navigator, 'clipboard', { value: { writeText: () => Promise.resolve() } }))
})

test('全卡 wide 常驻、读屏全文与视觉打字分离；动作回 wide、离开不打断', async ({ page }) => {
  await page.goto('/')
  const c = card(page), bot = c.getByTestId('live-bot'), bubble = c.getByTestId('pitch-bubble')
  await bot.evaluate((el) => el.addEventListener('bz-play', (event) => {
    el.dataset.lastPlay = `${event.detail.state}:${event.detail.hold}`
  }))
  // 介绍上面盖着整卡链接（整张卡可点），所以不等「介绍自己接到指针」，直接把鼠标移到介绍的位置。
  await c.locator('.bot-tagline').hover({ force: true })
  await expect(bot).toHaveAttribute('data-last-play', 'wide:Infinity')
  await expect(bot).toHaveAttribute('data-state', 'wide')
  await expect(bubble.getByTestId('typing')).toBeVisible()
  const text = await bubble.getAttribute('data-text')
  await expect(c.locator('.bz-sr-only').filter({ hasText: text })).toHaveText(text)
  await expect(bubble.locator('span')).toHaveCount(1)
  await expect(bubble.locator('span')).toHaveText(text)
  await c.getByTestId('btn-prompt').click()
  await expect(bot).toHaveAttribute('data-state', 'wink')
  await expect(bot).toHaveAttribute('data-state', 'wide', { timeout: 2500 })
  await page.waitForTimeout(2200)
  await expect(bot).toHaveAttribute('data-state', 'wide')
  await c.getByTestId('avatar').click()
  expect(POKE_PITCHES).toContain(await bubble.getAttribute('data-text'))
  const state = await bot.getAttribute('data-state')
  await page.mouse.move(0, 0)
  await expect(bubble).toHaveAttribute('data-open', 'false')
  await page.waitForTimeout(200)
  await expect(bot).toHaveAttribute('data-state', state)
  await expect(bot).toHaveAttribute('data-state', 'idle', { timeout: 4000 })
})

test('身体填色只由根 SVG 的主题变量控制，动画帧不覆盖内联变量', async ({ page }) => {
  await page.goto('/')
  const bot = card(page).getByTestId('live-bot'), fill = bot.locator('[data-part="fill"]')
  await page.evaluate(() => document.documentElement.classList.remove('dark'))
  const light = await fill.evaluate((el) => getComputedStyle(el).fill)
  await bot.evaluate((el) => el.style.setProperty('--bz-bot-dark', '#f1efe9'))
  await page.waitForTimeout(250)
  await expect(fill).toHaveCSS('fill', light)
  await page.evaluate(() => document.documentElement.classList.add('dark'))
  await expect(fill).toHaveCSS('fill', 'rgb(241, 239, 233)')
  await page.waitForTimeout(250)
  await expect(fill).toHaveCSS('fill', 'rgb(241, 239, 233)')
})

test('详情按钮只驱动本地 Bot，导入上报/新页与复制播报仍正常', async ({ page, context }) => {
  await page.goto(`/bots/${slug}`)
  const bot = page.getByTestId('live-bot')
  await page.getByTestId('btn-prompt').click()
  await expect(bot).toHaveAttribute('data-state', 'wink')
  await expect(page.locator('[aria-live="polite"]')).toHaveText('已复制安装提示词')
  const popup = context.waitForEvent('page')
  const request = page.waitForRequest((r) => r.url().endsWith('/api/click') && r.postDataJSON().kind === 'import')
  await page.getByTestId('btn-import').click()
  await expect(bot).toHaveAttribute('data-state', 'comet')
  expect((await request).postDataJSON()).toEqual({ slug, kind: 'import' })
  await (await popup).close()
  await expect(bot).toHaveAttribute('data-state', 'idle', { timeout: 3500 })
})

test('减少动效中途切换：打字立即完成，静态帧不变；恢复后基础状态正确', async ({ page }) => {
  await page.goto('/')
  const c = card(page), bubble = c.getByTestId('pitch-bubble'), bot = c.getByTestId('live-bot')
  await c.locator('.bot-tagline').hover({ force: true })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(bubble.locator('span')).toHaveText(await bubble.getAttribute('data-text'))
  await expect(bubble.getByTestId('typing')).toHaveCount(0)
  await expect(bot).toHaveAttribute('data-state', 'idle')
  const before = await bot.innerHTML()
  await c.getByTestId('avatar').click()
  await page.waitForTimeout(400)
  expect(await bot.innerHTML()).toBe(before)
  expect(POKE_PITCHES).toContain(await bubble.getAttribute('data-text'))
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await expect(bot).toHaveAttribute('data-state', 'wide')
})
